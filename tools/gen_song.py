#!/usr/bin/env python3
"""Write dos/src/song.h: the music for the DOS edition, as tables the timer interrupt can play.
E minor, 112 beats a minute, sixteen steps to the bar, four bars to a section.
Tracks: 0 bass, 1 chord (upper), 2 chord (lower), 3 melody, 4 arpeggio, 5 drums (OPL2 rhythm voices).
A step is 0 = hold, 1 = note off, else a MIDI note number. A drum step is a bit mask (BD 16, SD 8, TOM 4, CYM 2, HH 1)."""
import pathlib
SEM = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
def tok(t):
    if t == '.': return 0
    if t == '-': return 1
    n = SEM[t[0]]; i = 1
    if t[i] == '#': n += 1; i += 1
    return n + (int(t[i:]) + 1) * 12
def bar(s):
    v = [tok(t) for t in s.split()]; assert len(v) == 16, (s, len(v)); return v
REST = '- . . . . . . . . . . . . . . .'
# ---- bass: low and chunky, with octave jumps
B_E  = 'E2 . - E2 . - E3 - E2 . - E2 - D3 E3 -'
B_E2 = 'E2 . - E2 . - E3 - E2 . - G2 . - A2 B2'
B_C  = 'C2 . - C2 . - C3 - C2 . - C2 - B2 C3 -'
B_D  = 'D2 . - D2 . - D3 - D2 . - D2 - F#2 A2 D3'
B_A  = 'A2 . . . . . . - - - A2 . . . - -'
B_B  = 'B2 . . . . . . - - - B2 . . . - -'
B_BU = 'B2 . . . . . . - B2 - B2 - D3 - F#3 -'
# ---- chord stabs: short, off the beat
def stab(n): return ' '.join(n if i in (3, 6, 11, 14) else '-' if i in (4, 7, 12, 15, 0) else '.' for i in range(16))
def hold(n): return n + ' . . . . . . . . . . . . . - -'
# ---- melody: comes in now and then; the D sharp and the long rests are the intrigue
M1 = ['B4 . . . - . E5 . D#5 . E5 . - . . .', 'G5 . . . . . F#5 . E5 . - . B4 . - .',
      'C5 . . . - . E5 . G5 . . . F#5 . E5 .', 'F#5 . . . . . . . - . A4 . D5 . F#5 -']
M2 = ['- . . . E5 . G5 . B5 . . . A5 . G5 .', 'F#5 . . . . . - . D#5 . . . E5 . . .',
      'C6 . B5 . G5 . E5 . - . . . G5 . E5 .', 'D5 . . . F#5 . . . A5 . . . . . - .']
def arp(ns): return ' '.join(ns[i % len(ns)] for i in range(16))
A_A = arp(['A4', 'C5', 'E5', 'G5', 'E5', 'C5']); A_B = arp(['B4', 'D5', 'F#5', 'A5', 'F#5', 'D5'])
A_FILL = '- . . . . . . . . . . . B5 G5 E5 B4'
# ---- drums
BD, SD, TOM, CYM, HH = 16, 8, 4, 2, 1
def drums(k, s, h, c=(), t=()):
    return [(BD if i in k else 0) | (SD if i in s else 0) | (HH if i in h else 0) | (CYM if i in c else 0) | (TOM if i in t else 0) for i in range(16)]
D_INTRO = drums((0, 8), (), (0, 2, 4, 6, 8, 10, 12, 14))
D_MAIN = drums((0, 3, 8, 10), (4, 12), (0, 2, 4, 6, 8, 10, 12, 14, 15))
D_MAIN_C = drums((0, 3, 8, 10), (4, 12), (2, 4, 6, 8, 10, 12, 14, 15), c=(0,))
D_FILL = drums((0, 3, 8), (4, 12, 14, 15), (0, 2, 4, 6, 8, 10), t=(11, 13))
D_HALF = drums((0, 10), (8,), (0, 2, 4, 6, 8, 10, 12, 14))
D_HALF_C = drums((0, 10), (8,), (2, 4, 6, 8, 10, 12, 14), c=(0,))
D_HALF_F = drums((0,), (8, 12, 14), (0, 2, 4, 6, 8, 10), t=(13, 15))
def sec(bass, hi, lo, mel, ar, dr):
    f = lambda bars: [x for b in bars for x in (bar(b) if isinstance(b, str) else b)]
    return [f(bass), f(hi), f(lo), f(mel), f(ar), f(dr)]
R4 = [REST] * 4
groove_b = [B_E, B_E2, B_C, B_D]
st_hi = [stab('D5'), stab('D5'), stab('E5'), stab('F#5')]; st_lo = [stab('G4'), stab('B4'), stab('G4'), stab('A4')]
SECT = [
 sec(groove_b, R4, R4, R4, R4, [D_INTRO, D_INTRO, D_MAIN, D_FILL]),                                   # 0 intro: bass and drums
 sec(groove_b, st_hi, st_lo, R4, [REST, REST, REST, A_FILL], [D_MAIN_C, D_MAIN, D_MAIN, D_FILL]),      # 1 groove with stabs
 sec(groove_b, st_hi, st_lo, M1, R4, [D_MAIN_C, D_MAIN, D_MAIN, D_MAIN]),                              # 2 melody
 sec([B_A, B_A, B_B, B_BU], [hold('E5'), hold('E5'), hold('F#5'), hold('F#5')], [hold('C5'), hold('G4'), hold('D5'), hold('A4')],
     R4, [A_A, A_A, A_B, A_B], [D_HALF_C, D_HALF, D_HALF, D_HALF_F]),                                  # 3 break: half time, held chords, arpeggio
 sec(groove_b, st_hi, st_lo, M2, R4, [D_MAIN_C, D_MAIN, D_MAIN, D_FILL]),                              # 4 melody, the answer
 sec(groove_b, R4, R4, R4, R4, [D_MAIN, D_MAIN, D_MAIN, D_MAIN]),                                      # 5 bass and drums, for the bench
]
out = ['/* Generated by tools/gen_song.py. Do not edit. */', '#define SONG_NSEC %d' % len(SECT), '#define SONG_STEPS 64',
       'static const u8 song_sec[SONG_NSEC][6][SONG_STEPS] = {']
for s in SECT:
    out.append(' {')
    for t in s:
        assert len(t) == 64
        out.append('  {' + ','.join(str(v) for v in t) + '},')
    out.append(' },')
out += ['};',
        'static const u8 order_title[] = { 0, 1, 2, 1, 3, 4, 1, 3 };',
        'static const u8 order_bench[] = { 5, 1, 5, 3, 1, 2, 5, 3 };']
(pathlib.Path(__file__).resolve().parent.parent / 'dos' / 'src' / 'song.h').write_text('\n'.join(out) + '\n')
print('wrote song.h:', len(SECT), 'sections')
