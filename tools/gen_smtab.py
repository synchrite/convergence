#!/usr/bin/env python3
"""Write dos/src/sm_tab.c: the tables the slow-motion view needs, so the DOS program does no
floating point. Physics as in archive/slowmo-prototype/index.html:
  gun: speed from the voltage fallen through, with relativity;
  phosphor: single-scattering Monte Carlo (screened Rutherford cross-section, Joy-Luo energy loss)."""
import math, pathlib
C = 2.99792458e8
def beta(T): g = 1 + T / 511.0; return math.sqrt(1 - 1 / (g * g))       # T in keV
def lerp(N, x):
    for (x0, y0), (x1, y1) in zip(N, N[1:]):
        if x <= x1: return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return N[-1][1]
VN = [(0, 0), (1, 0.010), (3, 0.6), (6, 7), (26, 7), (31, 25), (62, 25)]          # mm, kV on the axis
WN = [(0, 0.30), (1.6, 0), (6, -0.6), (25, -1.5), (45, -1.1), (62, -0.9)]         # beam half-width, mm
out = ['/* Generated by tools/gen_smtab.py. Do not edit. */', '#include "sm.h"']
def arr(decl, vals, per=12):
    out.append(decl + ' = {')
    for i in range(0, len(vals), per): out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')
SM_N = 497
xs = [i / 8 for i in range(SM_N)]
arr('const unsigned short sm_gun_v[%d]' % SM_N, [max(1, round(beta(lerp(VN, x) + 1e-4) * C * 1e-12 * 65536 * 4096)) for x in xs])
arr('const unsigned short sm_gun_ev[%d]' % SM_N, [min(65535, round(lerp(VN, x) * 1000)) for x in xs])
arr('const short sm_gun_w[%d]' % SM_N, [round(lerp(WN, x) * 256) for x in xs])
NB = 64
E = [0.3 * (25.6 / 0.3) ** (i / (NB - 1)) for i in range(NB)]                     # keV
arr('const unsigned short sm_e[%d]' % NB, [round(e * 1000) for e in E])
arr('const unsigned short sm_vel[%d]' % NB, [round(beta(e) * C * 1e-6 * 256) for e in E])   # nm per fs, x256
mats = [('Al', 13, 26.98, 2.70), ('ZnS', 23, 48.7, 4.09), ('Y2O2S', 22, 48.4, 4.9)]
lam, de, al = [], [], []
for name, Z, A, rho in mats:
    J = (9.76 * Z + 58.5 * Z ** -0.19) * 1e-3
    for e in E:
        a = 3.4e-3 * Z ** 0.67 / e
        sig = 5.21e-21 * (Z * Z / (e * e)) * (4 * math.pi / (a * (1 + a))) * ((e + 511) / (e + 1024)) ** 2
        lam.append(max(1, round(A / (6.022e23 * rho * sig) * 1e7 * 16 * 16)))     # mean free path, nm x256
        de.append(round(78500 * rho * Z / (A * e) * math.log(1.166 * (e + 0.85 * J) / J) * 1e-4 * 256))   # eV per nm, x256
        al.append(round(a * 65536))
arr('const unsigned short sm_lam[3][%d]' % NB, lam); arr('const unsigned short sm_de[3][%d]' % NB, de); arr('const unsigned short sm_al[3][%d]' % NB, al)
arr('const unsigned short sm_ln[256]', [round(-math.log((i + 0.5) / 256) * 256) for i in range(256)])
text = '\n'.join(out) + '\n'
(pathlib.Path(__file__).resolve().parent.parent / 'dos' / 'src' / 'sm_tab.c').write_text(text)
print('wrote sm_tab.c;', 'lambda nm at 25 keV:', [round(lam[k * NB + NB - 1] / 256, 1) for k in range(3)], 'at 0.3 keV:', [round(lam[k * NB] / 256, 2) for k in range(3)],
      'dE/ds eV/nm at 25 keV:', [round(de[k * NB + NB - 1] / 256, 2) for k in range(3)], 'max de', max(de), 'max lam', max(lam), 'max al', max(al))
